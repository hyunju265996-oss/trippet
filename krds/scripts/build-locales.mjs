// Regenerates locales/bundle.js from locales/*.json (used only when index.html is opened via file://).
// Run: node scripts/build-locales.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'locales');
const out = {};
for (const l of ['ko', 'en', 'zh', 'ja']) out[l] = JSON.parse(readFileSync(join(dir, `${l}.json`), 'utf8'));
writeFileSync(join(dir, 'bundle.js'), '/* generated by scripts/build-locales.mjs — edit the JSON files instead */\nwindow.__KRDS_LOCALES__ = ' + JSON.stringify(out) + ';\n');
console.log('wrote locales/bundle.js');
